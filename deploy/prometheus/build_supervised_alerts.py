#!/usr/bin/env python3
"""Generate vmware-alerts-supervised.yml and pryorda-alerts-supervised.yml.

Same rules as vmware-alerts.yml and pryorda-alerts.yml, but the rules about VMs (group vmware-vm,
all of pryorda's) and the vCenter alarms raised on a VM only fire for the VMs carrying a given
vSphere tag. Needs `collectors: {tags: true}` and the category under `tags: {categories: [...]}`.
Load these files INSTEAD of the original ones.

Regenerate:  python3 build_supervised_alerts.py [--category supervision] [--tag true]
"""
import argparse
import os
import re

HEADER = """# GENERATED by build_supervised_alerts.py from %s: do not edit.
# Load this file INSTEAD of %s: VM alerts only fire for the VMs tagged %s=%s.
"""
EXPR = re.compile(r"^(\s+expr: )(.+)$")
# expr possibly folded on several lines, up to the rule's "for:"
PRYORDA_EXPR = re.compile(r"^( +expr: )(.+?)\n(?= +for:)", re.M | re.S)
GROUP = re.compile(r"^  - name: (\S+)$")


def supervised(rules, category, tag):
    tagged = f'vmware_vm_tag{{category="{category}", tag="{tag}"}}'
    moid = f'label_replace({tagged}, "entity_moid", "$1", "vm_moid", "(.*)")'
    alarm = "vmware_alarm_triggered{"
    out, group, changed = [], None, 0
    for line in rules.splitlines():
        g, e = GROUP.match(line), EXPR.match(line)
        if g:
            group = g.group(1)
        if e and group == "vmware-vm":
            line = f"{e.group(1)}({e.group(2)}) and on(vcenter, vm_moid) {tagged}"
            changed += 1
        elif e and alarm in e.group(2):
            other = e.group(2).replace(alarm, alarm + 'entity_type!="VirtualMachine", ')
            vm = e.group(2).replace(alarm, alarm + 'entity_type="VirtualMachine", ')
            line = f"{e.group(1)}({other}) or (({vm}) and on(vcenter, entity_moid) {moid})"
            changed += 1
        out.append(line)
    return "\n".join(out) + "\n", changed


def pryorda_supervised(rules, category, tag):
    """pryorda's series have no vm_moid: join on the VM name (same-named VMs share their fate)."""
    tagged = f'vmware_vm_tag{{category="{category}", tag="{tag}"}}'

    def filtered(e):
        expr = " ".join(e.group(2).split())
        return f"{e.group(1)}({expr}) and on(vcenter, vm_name) {tagged}\n"

    return PRYORDA_EXPR.subn(filtered, rules.replace("), unchanged,", "), filtered on a tag,", 1))


def generate(here, source, target, build, args):
    with open(os.path.join(here, source), encoding="utf-8") as f:
        text, changed = build(f.read(), args.category, args.tag)
    if changed == 0:
        raise SystemExit(f"{source}: no rule changed")
    path = os.path.join(here, target)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER % (source, source, args.category, args.tag) + text)
    print(f"wrote {path} ({changed} rules filtered)")


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--category", default="supervision")
    ap.add_argument("--tag", default="true")
    args = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    generate(here, "vmware-alerts.yml", "vmware-alerts-supervised.yml", supervised, args)
    generate(here, "pryorda-alerts.yml", "pryorda-alerts-supervised.yml", pryorda_supervised, args)


if __name__ == "__main__":
    main()
