#!/usr/bin/env python3
"""Generate vmware-alerts-supervised.yml from vmware-alerts.yml.

Same rules, but the rules about VMs (group vmware-vm) and the vCenter alarms raised on a VM
only fire for the VMs carrying a given vSphere tag. Needs `collectors: {tags: true}` and the
category under `tags: {categories: [...]}`. Load this file INSTEAD of vmware-alerts.yml.

Regenerate:  python3 build_supervised_alerts.py [--category supervision] [--tag true]
"""
import argparse
import os
import re

HEADER = """# GENERATED by build_supervised_alerts.py from vmware-alerts.yml: do not edit.
# Load this file INSTEAD of vmware-alerts.yml: VM alerts only fire for the VMs tagged %s=%s.
"""
EXPR = re.compile(r"^(\s+expr: )(.+)$")
GROUP = re.compile(r"^  - name: (\S+)$")


def supervised(rules, category, tag):
    tagged = f'vmware_vm_tag{{category="{category}", tag="{tag}"}}'
    moid = f'label_replace({tagged}, "entity_moid", "$1", "vm_moid", "(.*)")'
    alarm = "vmware_alarm_triggered{"
    out, group, changed = [], None, 0
    for line in rules.splitlines():
        g, e = GROUP.match(line), EXPR.match(line)
        if g:
            group = g.group(1)
        if e and group == "vmware-vm":
            line = f"{e.group(1)}({e.group(2)}) and on(vcenter, vm_moid) {tagged}"
            changed += 1
        elif e and alarm in e.group(2):
            other = e.group(2).replace(alarm, alarm + 'entity_type!="VirtualMachine", ')
            vm = e.group(2).replace(alarm, alarm + 'entity_type="VirtualMachine", ')
            line = f"{e.group(1)}({other}) or (({vm}) and on(vcenter, entity_moid) {moid})"
            changed += 1
        out.append(line)
    if changed == 0:
        raise SystemExit("no rule changed")
    return "\n".join(out) + "\n", changed


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--category", default="supervision")
    ap.add_argument("--tag", default="true")
    args = ap.parse_args()
    here = os.path.dirname(os.path.abspath(__file__))
    with open(os.path.join(here, "vmware-alerts.yml"), encoding="utf-8") as f:
        text, changed = supervised(f.read(), args.category, args.tag)
    path = os.path.join(here, "vmware-alerts-supervised.yml")
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEADER % (args.category, args.tag) + text)
    print(f"wrote {path} ({changed} rules filtered)")


if __name__ == "__main__":
    main()
